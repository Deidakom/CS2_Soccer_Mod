#!/usr/bin/env node
// SoccerMod Arena: writes SoccerModMvpPlugin.ArenaStandBoards.cs - where the plugin's LED boards stand
// on soccer_soccermod_arena. 2026-10-18 owner: "remove the LED walls on the pitch, keep them default as
// black walls ... and the banners under the tribune, replace them with LED walls": the boards cover the
// printed advert band on the lower stand's front wall (PARAPET.adLow-adHigh), the tunnel heads left open.
//
//   node tools/arena/generate-arena-standboards.mjs [out.cs]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RING, P, PARAPET } from "./layout.mjs";

const BOARD = { width: 320, height: 50 };   // the LED board model at scale 1 (AtmoBoards.cs), origin bottom centre
const out = process.argv[2] ?? path.join(path.dirname(fileURLToPath(import.meta.url)), "../../src/server-plugin/SoccerModMvp/SoccerModMvpPlugin.ArenaStandBoards.cs");
const { N, kinds } = RING, f = (v) => `${Number(v.toFixed(2))}f`, deg = (r) => r * 180 / Math.PI;
const D = -1.5, wantScale = (PARAPET.adHigh - PARAPET.adLow) / BOARD.height;

// runs of stand front between the tunnel heads, in ring order (counter-clockwise)
const start = kinds.findIndex((k, i) => k !== "tunnel" && kinds[(i + N - 1) % N] === "tunnel");
const runs = [];
for (let n = 0, cur = null; n < N; n++) {
  const i = (start + n) % N;
  if (kinds[i] === "tunnel") { cur = null; continue; }
  if (!cur) runs.push(cur = []);
  cur.push(i);
}
const boards = [];
for (const run of runs) {
  const dense = [];
  for (const i of run) for (let k = 0; k < 16; k++) dense.push(P(i + k / 16, D, 0));
  dense.push(P(run.at(-1) + 1, D, 0));
  const cum = [0]; for (let k = 1; k < dense.length; k++) cum.push(cum[k - 1] + Math.hypot(dense[k][0] - dense[k - 1][0], dense[k][1] - dense[k - 1][1]));
  const total = cum.at(-1), count = Math.max(1, Math.round(total / (BOARD.width * wantScale)));
  const at = (s) => { let lo = 0, hi = dense.length - 1; while (hi - lo > 1) { const m = (lo + hi) >> 1; if (cum[m] <= s) lo = m; else hi = m; } const t = (s - cum[lo]) / (cum[hi] - cum[lo] || 1); return [dense[lo][0] + (dense[hi][0] - dense[lo][0]) * t, dense[lo][1] + (dense[hi][1] - dense[lo][1]) * t]; };
  for (let k = 0; k < count; k++) {
    const a = at(total * k / count), b = at(total * (k + 1) / count), chord = Math.hypot(b[0] - a[0], b[1] - a[1]);
    // chord counter-clockwise, the pitch on its left: the board faces it (AtmoBoardSpots: +x wall = yaw 180)
    boards.push({ x: (a[0] + b[0]) / 2, y: (a[1] + b[1]) / 2, yaw: deg(Math.atan2(b[0] - a[0], -(b[1] - a[1]))), scale: chord / BOARD.width });
  }
}
// boards a little higher than the band are centred on it (the cap above and the wall below hide nothing)
const z = (s) => (PARAPET.adLow + PARAPET.adHigh) / 2 - BOARD.height * s / 2;

const cs = `using CounterStrikeSharp.API.Modules.Utils;

namespace SoccerModMvp;

// GENERATED by tools/arena/generate-arena-standboards.mjs from tools/arena/layout.mjs - do not edit by hand.
// 2026-10-18 owner: on soccer_soccermod_arena the LED boards stand on the lower stand's front wall over the
// printed adverts (${boards.length} boards, ${runs.length} runs between the tunnel heads); the pitch keeps the map's black boards.
public sealed partial class SoccerModMvpPlugin
{
    private static readonly (float X, float Y, float Z, float Yaw, float Scale)[] ArenaStandBoards =
    {
${boards.map((b) => `        (${f(b.x)}, ${f(b.y)}, ${f(z(b.scale))}, ${f(b.yaw)}, ${f(b.scale)}),`).join("\n")}
    };

    private static IEnumerable<(Vector At, float Yaw, float Scale)> ArenaStandBoardSpots()
    {
        foreach (var (x, y, z, yaw, scale) in ArenaStandBoards) yield return (new Vector(x, y, z), yaw, scale);
    }
}
`;
fs.writeFileSync(out, cs);
console.log(`${out}: ${boards.length} boards in ${runs.length} runs, scale ${Math.min(...boards.map((b) => b.scale)).toFixed(3)}-${Math.max(...boards.map((b) => b.scale)).toFixed(3)} (band wants ${wantScale.toFixed(3)})`);
