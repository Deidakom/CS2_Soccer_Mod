#!/usr/bin/env node
// SoccerMod Arena: writes SoccerModMvpPlugin.ArenaLayout.cs - every number the plugin needs on
// soccer_soccermod_arena (LED ring spots, banner hooks, spidercam anchors, score screens, crowd
// rows for flares), taken from tools/arena/layout.mjs so map and plugin cannot drift apart.
//
//   node tools/arena/generate-arena-plugin.mjs [out.cs]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RING, P, station, roofZ, roofD, lowerRow, CURVE, FASCIA, PARAPET } from "./layout.mjs";
import { buildArena } from "./geometry.mjs";

const RING_SEGMENT = { length: 160, height: 40 };   // models/soccermod_arena/light_ring (generate-arena-plugin-assets.mjs)
const out = process.argv[2] ?? path.join(path.dirname(fileURLToPath(import.meta.url)), "../../src/server-plugin/SoccerModMvp/SoccerModMvpPlugin.ArenaLayout.cs");
const { N } = RING, f = (v) => `${Number(v.toFixed(2))}f`, deg = (r) => r * 180 / Math.PI;
const inwardYaw = (i) => { const a = station(Math.floor(i)), b = station(Math.floor(i) + 1), t = i - Math.floor(i); return deg(Math.atan2(-(a.ny + (b.ny - a.ny) * t), -(a.nx + (b.nx - a.nx) * t))); };

// ---- LED ring: equal segments along the fascia, 1.5 units proud of it --------------------------
const ringD = FASCIA.d - 1.5, ringZ = (FASCIA.ledLow + FASCIA.ledHigh) / 2;
const dense = []; for (let k = 0; k <= N * 16; k++) dense.push(P(k / 16, ringD, ringZ));
const cum = [0]; for (let k = 1; k < dense.length; k++) cum.push(cum[k - 1] + Math.hypot(dense[k][0] - dense[k - 1][0], dense[k][1] - dense[k - 1][1]));
const total = cum.at(-1), count = Math.round(total / RING_SEGMENT.length);
const at = (s) => { let lo = 0, hi = dense.length - 1; while (hi - lo > 1) { const m = (lo + hi) >> 1; if (cum[m] <= s) lo = m; else hi = m; } const t = (s - cum[lo]) / (cum[hi] - cum[lo]); return [dense[lo][0] + (dense[hi][0] - dense[lo][0]) * t, dense[lo][1] + (dense[hi][1] - dense[lo][1]) * t]; };
const ring = [];
for (let k = 0; k < count; k++) {
  const a = at(total * k / count), b = at(total * (k + 1) / count), mx = (a[0] + b[0]) / 2, my = (a[1] + b[1]) / 2, chord = Math.hypot(b[0] - a[0], b[1] - a[1]);
  // the chord runs counter-clockwise; the pitch is on its left
  const yaw = deg(Math.atan2(b[0] - a[0], -(b[1] - a[1])));
  // a straight segment on a curved wall: push its middle out by the sagitta so its ends do not dip into the fascia
  const mid = at(total * (k + 0.5) / count), sag = Math.hypot(mid[0] - mx, mid[1] - my);
  ring.push({ x: mx - Math.cos(yaw * Math.PI / 180) * 0, y: my, z: ringZ, yaw, scale: (chord - 2) / RING_SEGMENT.length, sag });
}
// ---- roof edge: banner hooks and spidercam anchors ------------------------------------------------
const edgeD = roofD(1) + 2;
const stationAtX = (x, north) => { let best = 0, bd = 1e9; for (let k = 0; k <= N * 16; k++) { const p = P(k / 16, edgeD, 0); if ((p[1] > 0) !== north) continue; const d = Math.abs(p[0] - x); if (d < bd) { bd = d; best = k / 16; } } return best; };
const banners = [];
for (const side of [1, -1]) for (const x of [-1100, -546, 546, 1100]) {
  const i = stationAtX(x, side > 0), p = P(i, edgeD - 4, roofZ(Math.round(i), 1) - 34);
  banners.push({ x: p[0], y: p[1], z: p[2], yaw: inwardYaw(i) + 90, key: `${side}:${x}` });
}
const anchors = [45, 135, 225, 315].map((a) => { let best = 0, bd = 1e9; for (let i = 0; i < N; i++) { const s = station(i), d = Math.abs(((deg(Math.atan2(s.ny, s.nx)) - a + 540) % 360) - 180); if (d < bd) { bd = d; best = i; } } return P(best, roofD(1) + 10, roofZ(best, 1) - 32); });
const { screens } = buildArena();
const north = screens.find((s) => s.end === "north");
const rowZ = lowerRow(0).z + 15, rowD = (lowerRow(0).d0 + lowerRow(0).d1) / 2;
const centre = (i) => P(i, FASCIA.d, 0);

const cs = `using CounterStrikeSharp.API;
using CounterStrikeSharp.API.Modules.Utils;

namespace SoccerModMvp;

// GENERATED by tools/arena/generate-arena-plugin.mjs from tools/arena/layout.mjs - do not edit by hand.
//
// soccer_soccermod_arena, for two Workshop updates called ka_soccermod_stadium (2026-10-01, owner: "an own version of the v8 stadium, round, realistic,
// as a separate map" and "make sure our mod and all its visual changes work on the new map").
// The pitch is v8's to the unit (grass, lines, goals, nets, low boards, invisible walls, dugouts),
// so everything that happens on the pitch runs as on v8. The stands, roof and screens are new:
// the stadium effects take their spots from here on that map. v8 keeps its own numbers.
public sealed partial class SoccerModMvpPlugin
{
    // 2026-10-02 owner: the map is called soccer_soccermod_arena again ("the name was better"). Workshop
    // updates 3 and 4 carried it as ka_soccermod_stadium; both names count, so a server still on an old
    // revision keeps working.
    private const string ArenaMapName = "soccer_soccermod_arena";
    private const string ArenaFirstMapName = "ka_soccermod_stadium";
    private static bool IsArenaMap(string? map) => string.Equals(map, ArenaMapName, StringComparison.OrdinalIgnoreCase)
        || string.Equals(map, ArenaFirstMapName, StringComparison.OrdinalIgnoreCase);
    // during the map (the hot paths); while a map loads _currentMapName is still the old one: use ArenaLoading there
    private bool OnArena => IsArenaMap(_currentMapName);
    private static bool ArenaLoading => IsArenaMap(Server.MapName);

    // Owner 2026-10-01: the arena's goals stand where CS:S (ka_soccer_xsl_stadium_b1) has them, 7 units
    // further out than v8's (post front |y| 1384 instead of 1377; width and height are the same).
    // Everything measured from a goal - detection plane, goal frame, moving net, net pocket, post
    // sounds, keeper box - moves with it. The painted lines did not move.
    private const float ArenaGoalShift = 7f;
    private float GoalShiftY => OnArena ? ArenaGoalShift : 0f;

    private static string ArenaRadarTextureResource => "panorama/images/overheadmaps/"
        + (string.Equals(Server.MapName, ArenaFirstMapName, StringComparison.OrdinalIgnoreCase) ? ArenaFirstMapName : ArenaMapName) + "_radar_psd.vtex";
    private const string ArenaCrowdDir = "models/soccermod/atmo/crowd_arena/";
    private const string ArenaRingModel = "models/soccermod_arena/light_ring.vmdl";
    // the four pitch designs as geometry with tiling 12-texel-per-unit grass (index = design - 1)
    private static readonly string[] ArenaPitchDesignModels =
    {
        "models/soccermod_arena/pitch_design_stripes.vmdl", "models/soccermod_arena/pitch_design_lengthwise.vmdl",
        "models/soccermod_arena/pitch_design_diamond.vmdl", "models/soccermod_arena/pitch_design_circles.vmdl",
    };

    // LED ring: ${count} segments of ${RING_SEGMENT.length} x ${RING_SEGMENT.height} on the upper stand's fascia (z ${FASCIA.ledLow}-${FASCIA.ledHigh}),
    // counter-clockwise from the middle of the east side, facing the pitch.
    private static readonly (float X, float Y, float Yaw, float Scale)[] ArenaRingSpotTable =
    {
${ring.map((r) => `        (${f(r.x)}, ${f(r.y)}, ${f(r.yaw)}, ${f(r.scale)}),`).join("\n")}
    };
    private const float ArenaRingZ = ${f(ringZ)};
    private static IEnumerable<(Vector At, float Yaw, float Scale)> ArenaRingSpots()
    {
        foreach (var (x, y, yaw, scale) in ArenaRingSpotTable) yield return (new Vector(x, y, ArenaRingZ), yaw, scale);
    }

    // Waving banners: under the roof edge at both ends, left and right of the video wall.
    // Same order as on v8: the +y end first, x -1100, -546, 546, 1100.
    private static readonly (float X, float Y, float Z, float Yaw)[] ArenaBannerSpots =
    {
${banners.map((b) => `        (${f(b.x)}, ${f(b.y)}, ${f(b.z)}, ${f(b.yaw)}),`).join("\n")}
    };

    // Spidercam cables: the roof's inner edge at the four corners.
    private static readonly Vector[] ArenaSpiderAnchors =
    {
${anchors.map((a) => `        new(${f(a[0])}, ${f(a[1])}, ${f(a[2])}),`).join("\n")}
    };

    // Score screens: two upright video walls (800 x 200) under the roof edge; the picture has a red
    // and a blue score box 70 units left and right of this point, 117 wide and 115 high.
    private const float ArenaScoreScreenY = ${f(Math.abs(north.score[1]))};
    private const float ArenaScoreCenterZ = ${f(north.score[2])};
    private const float ArenaScoreScale = 1.35f;   // numbers and GOALLL!! this much bigger than on v8's small roof screens

    // Stands: front of the lower stand |x/${CURVE.A}|^${CURVE.EXP} + |y/${CURVE.B}|^${CURVE.EXP} = 1; the first row of seats lies
    // ${rowD} units behind it at z ${rowZ - 15}.
    private static readonly (float X, float Y)[] ArenaStandCentres = { (${f(centre(0)[0])}, 0f), (${f(centre(N / 2)[0])}, 0f), (0f, ${f(centre(N / 4)[1])}), (0f, ${f(centre(3 * N / 4)[1])}) };
    private static Vector ArenaRowSpot(float x, float y, bool end, float behind, float z)
    {
        const float a = ${CURVE.A}f, b = ${CURVE.B}f, e = ${CURVE.EXP}f;
        // the point of the front curve at this x (ends) or y (sides), then out along the curve normal
        float cx, cy;
        if (end) { cx = Math.Clamp(x, -a * 0.98f, a * 0.98f); cy = MathF.Sign(y) * b * MathF.Pow(1f - MathF.Pow(MathF.Abs(cx) / a, e), 1f / e); }
        else { cy = Math.Clamp(y, -b * 0.98f, b * 0.98f); cx = MathF.Sign(x) * a * MathF.Pow(1f - MathF.Pow(MathF.Abs(cy) / b, e), 1f / e); }
        var nx = MathF.Sign(cx) * MathF.Pow(MathF.Abs(cx), e - 1f) / MathF.Pow(a, e);
        var ny = MathF.Sign(cy) * MathF.Pow(MathF.Abs(cy), e - 1f) / MathF.Pow(b, e);
        var len = MathF.Sqrt(nx * nx + ny * ny);
        return new Vector(cx + nx / len * behind, cy + ny / len * behind, z);
    }

    // ---- what the stadium modules ask (v8 numbers stay where they were measured) ---------------
    // flares in the fans' front row behind a goal (v8: lower tier front row y +-2074, z 107)
    private Vector AtmoEndRowSpot(float x, int fanSign) => OnHall ? HallEndRowSpot(x, fanSign) : OnArena ? ArenaRowSpot(x, fanSign, true, ${f(rowD)}, ${f(rowZ)}) : new Vector(x, fanSign * 2074f, 122f);
    // flares along a side stand's front row (v8: |x| 1716)
    private Vector AtmoSideRowSpot(float sideX, float y) => OnHall ? HallSideRowSpot(sideX, y) : OnArena ? ArenaRowSpot(sideX, y, false, ${f(rowD)}, ${f(rowZ)}) : new Vector(sideX, y, 122f);
    // confetti cannons at the foot of the fans' end
    private Vector AtmoCannonSpot(float sideSign, int fanSign) => OnHall ? HallCannonSpot(sideSign, fanSign) : OnArena ? ArenaRowSpot(sideSign * 1150f, fanSign, true, 5f, ${f(PARAPET.top + 8)}) : new Vector(sideSign * 1300f, fanSign * 1962f, 185f);
    // waving banners (v8: on the roof fascia, y +-1956, z 880.5); x is one of AtmoBannerXs
    private (Vector At, float Yaw) AtmoBannerSpot(float x, int side)
    {
        if (!OnArena) return (new Vector(x, side * 1956f, 880.5f), side > 0 ? 0f : 180f);
        var i = (side > 0 ? 0 : 4) + (x < -800f ? 0 : x < 0f ? 1 : x < 800f ? 2 : 3);
        var (bx, by, bz, yaw) = ArenaBannerSpots[i];
        return (new Vector(bx, by, bz), yaw);
    }
}
`;
fs.writeFileSync(out, cs);
console.log(`${out}: ring ${count} segments (max sagitta ${Math.max(...ring.map((r) => r.sag)).toFixed(2)}), 8 banners, 4 anchors, score screen y ${Math.abs(north.score[1]).toFixed(1)} z ${north.score[2].toFixed(1)}`);
