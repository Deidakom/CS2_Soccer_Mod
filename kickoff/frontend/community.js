const ROLE_CLASS = { GK: "gk", DEF: "def", MID: "mid", WING: "wing" };
const ROLE_SHORT = { GK: "GK", DEF: "DF", MID: "MF", WING: "WG" };
const $ = selector => document.querySelector(selector);
const $$ = selector => [...document.querySelectorAll(selector)];
const escapeHTML = value => String(value).replace(/[&<>'"]/g, character => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" })[character]);
const initials = name => String(name || "").replace(/[^a-z0-9]/gi, "").slice(0, 2).toUpperCase() || "SM";
let locale = COPY[localStorage.getItem("kickoff-language")] ? localStorage.getItem("kickoff-language") : "en";
let colorMode = localStorage.getItem("kickoff-color-mode") || (window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark");
let communityData = null;
const t = (key, values = {}) => (COPY[locale][key] || COPY.en[key] || key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
const roleLabel = role => t(`role.${role}`);
const formatNumber = value => new Intl.NumberFormat(locale).format(Number(value) || 0);

function updateModeToggle() {
  const nextLabel = colorMode === "dark" ? t("theme.light") : t("theme.dark");
  $("#colorModeToggle").setAttribute("aria-label", nextLabel);
  $("#colorModeToggle").title = nextLabel;
  $("#colorModeToggle span").textContent = colorMode === "dark" ? "☼" : "☾";
}

function applyColorMode(mode) {
  colorMode = mode === "light" ? "light" : "dark";
  localStorage.setItem("kickoff-color-mode", colorMode);
  document.documentElement.dataset.mode = colorMode;
  document.documentElement.dataset.theme = "blue";
  $("meta[name='theme-color']").content = colorMode === "light" ? "#f3f5f7" : "#0d1726";
  updateModeToggle();
}

function applyLanguage(language) {
  locale = COPY[language] ? language : "en";
  localStorage.setItem("kickoff-language", locale);
  document.documentElement.lang = locale;
  document.title = t("site.title");
  $$('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
  $$('[data-i18n-aria]').forEach(element => { element.setAttribute("aria-label", t(element.dataset.i18nAria)); });
  $$('[data-language]').forEach(button => button.classList.toggle("active", button.dataset.language === locale));
  updateModeToggle();
  renderCommunity();
}

function renderCommunity() {
  if (!communityData) {
    $("#communityDataSource span:last-child").textContent = t("community.loading");
    return;
  }
  const mod = communityData.soccermod || {};
  const gameplay = mod.gameplay || {};
  const sourcePill = $("#communityDataSource");
  sourcePill.classList.toggle("offline", !mod.available);
  sourcePill.querySelector("span:last-child").textContent = t(mod.available ? "community.live" : "community.unavailable");
  $("#statCapsPlayed").textContent = formatNumber(communityData.capsPlayed);
  $("#statRegistered").textContent = formatNumber(mod.registeredPlayers);
  $("#statActivePlayers").textContent = t("community.active", { count: formatNumber(mod.activePlayers30d) });
  $("#statAppearances").textContent = formatNumber(mod.matchAppearances);
  $("#statGoals").textContent = formatNumber(gameplay.goals);
  $("#statGoalSupport").textContent = t("community.assists", { count: formatNumber(gameplay.assists) });

  const preferences = communityData.positionPreferences || {};
  const sample = Object.values(preferences).reduce((sum, value) => sum + Number(value || 0), 0);
  $("#positionSample").textContent = t(sample === 1 ? "community.player" : "community.players", { count: formatNumber(sample) });
  $("#positionDistribution").innerHTML = Object.keys(ROLE_CLASS).map(role => {
    const count = Number(preferences[role] || 0);
    const percentage = sample ? Math.round(count / sample * 100) : 0;
    return `<div class="position-stat"><div class="position-stat-label"><span class="role-icon ${ROLE_CLASS[role]}">${ROLE_SHORT[role]}</span><b>${escapeHTML(roleLabel(role))}</b><span>${formatNumber(count)} · ${percentage}%</span></div><div class="position-track"><i style="width:${percentage}%"></i></div></div>`;
  }).join("");

  const activity = [
    ["community.passes", gameplay.passes], ["community.interceptions", gameplay.interceptions],
    ["community.saves", gameplay.saves], ["community.contacts", gameplay.hits],
    ["community.losses", gameplay.ballLosses], ["community.mvp", gameplay.mvp],
    ["community.motm", gameplay.motm], ["community.ownGoals", gameplay.ownGoals]
  ];
  $("#activityMetrics").innerHTML = activity.map(([label, value]) => `<div><span>${escapeHTML(t(label))}</span><strong>${formatNumber(value)}</strong></div>`).join("");
  const turnovers = Number(gameplay.interceptions || 0) + Number(gameplay.ballLosses || 0);
  $("#communityInsight span").textContent = turnovers
    ? t("community.recovery", { rate: Math.round(Number(gameplay.interceptions || 0) / turnovers * 100) })
    : t("community.noGameplay");

  const leaders = Array.isArray(mod.leaders) ? mod.leaders : [];
  $("#communityLeaderboard").innerHTML = leaders.length ? leaders.map((player, index) => `
    <div class="leader-row"><span class="leader-rank">${String(index + 1).padStart(2, "0")}</span><div class="avatar">${escapeHTML(initials(player.name))}</div><div class="leader-name"><b>${escapeHTML(player.name)}</b><small>${escapeHTML(t("community.matches", { count: formatNumber(player.matches) }))} · ${escapeHTML(t("community.goalsShort"))} ${formatNumber(player.goals)} · ${escapeHTML(t("community.assistsShort"))} ${formatNumber(player.assists)}</small></div><strong>${formatNumber(player.points)}</strong></div>`).join("")
    : `<div class="stats-empty"><span>01</span><p>${escapeHTML(t("community.noLeaders"))}</p></div>`;

  const recent = Array.isArray(communityData.recentCaps) ? communityData.recentCaps : [];
  $("#recentCaps").innerHTML = recent.length ? recent.map(cap => {
    const date = new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(new Date(cap.startedAt * 1000));
    const score = Number.isFinite(Number(cap.scoreCt)) && Number.isFinite(Number(cap.scoreT))
      ? `<small class="recent-cap-score">${Number(cap.scoreCt)}–${Number(cap.scoreT)}</small>` : "";
    return `<div class="recent-cap-row"><span class="game-chip">${escapeHTML(cap.game === "css" ? "CS:S" : "CS2")}</span><div><b>${escapeHTML(cap.map)}</b><small>${escapeHTML(date)}</small></div><strong>${score}${formatNumber(cap.players)}/12</strong></div>`;
  }).join("") : `<div class="stats-empty"><span>00</span><p>${escapeHTML(t("community.noCaps"))}</p></div>`;
}

async function loadCommunityStats() {
  try {
    const response = await fetch("/api/community/stats", { headers: { Accept: "application/json" }, credentials: "same-origin" });
    if (!response.ok) throw new Error("community_unavailable");
    communityData = await response.json();
  } catch {
    communityData = { capsPlayed: 0, positionPreferences: {}, recentCaps: [], soccermod: { available: false, gameplay: {}, leaders: [] } };
  }
  renderCommunity();
}

async function loadSteamSession() {
  const steamLink = $("#steamLogin");
  try {
    const response = await fetch("/api/me", { headers: { Accept: "application/json" }, credentials: "same-origin" });
    if (!response.ok) return;
    const profile = await response.json();
    if (!/^\d{17}$/.test(profile.steamid)) return;
    steamLink.textContent = profile.name || `Steam ${profile.steamid.slice(-6)}`;
    steamLink.href = "/";
  } catch {
    steamLink.textContent = t("steam.signin");
  }
}

